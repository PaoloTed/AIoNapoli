#!/usr/bin/env bash
set -eo pipefail

# -----------------------------------------------------------------------------
# Container Entrypoint Script
# Initializes and starts PostgreSQL 18, PostGIS, Cron service, and monthly tasks
# -----------------------------------------------------------------------------

PGVERSION="18"
PGCLUSTER="main"
PGDATA="${PGDATA:-/var/lib/postgresql/$PGVERSION/$PGCLUSTER}"
PGCONF_DIR="/etc/postgresql/$PGVERSION/$PGCLUSTER"
POSTGRES_DB="${POSTGRES_DB:-mobility}"
POSTGRES_USER="${POSTGRES_USER:-postgres}"
POSTGRES_PASSWORD="${POSTGRES_PASSWORD:-postgres}"
RUN_ON_STARTUP="${RUN_ON_STARTUP:-true}"

DOWNLOAD_LOG="/var/log/monthly-download.log"
PG_LOG="/var/log/postgresql/postgresql-$PGVERSION-$PGCLUSTER.log"

mkdir -p "$PGDATA" /var/log/postgresql /var/run/postgresql /data/gtfs /data/osm
chown -R postgres:postgres /var/lib/postgresql /var/log/postgresql /var/run/postgresql
chmod 0700 "$PGDATA"

echo "======================================================================"
echo " Starting Ubuntu Server Container with PostgreSQL 18 & PostGIS"
echo "======================================================================"

# 1. Initialize cluster if not present
if [ ! -s "$PGDATA/PG_VERSION" ] || [ ! -d "$PGCONF_DIR" ]; then
    echo "[ENTRYPOINT] Creating new PostgreSQL $PGVERSION cluster..."
    pg_dropcluster "$PGVERSION" "$PGCLUSTER" --stop 2>/dev/null || true
    pg_createcluster --locale=C.UTF-8 "$PGVERSION" "$PGCLUSTER"
fi

# 2. Configure network and authentication
echo "[ENTRYPOINT] Configuring postgresql.conf and pg_hba.conf..."
sed -i "s/#listen_addresses = 'localhost'/listen_addresses = '*'/g" "$PGCONF_DIR/postgresql.conf" || true
grep -q "listen_addresses = '*'" "$PGCONF_DIR/postgresql.conf" || echo "listen_addresses = '*'" >> "$PGCONF_DIR/postgresql.conf"

{
    echo "# Authentication configuration generated by entrypoint"
    echo "local   all             postgres                                trust"
    echo "local   all             all                                     trust"
    echo "host    all             all             127.0.0.1/32            trust"
    echo "host    all             all             ::1/128                 trust"
    echo "host    all             all             0.0.0.0/0               scram-sha-256"
    echo "host    all             all             ::/0                    scram-sha-256"
} > "$PGCONF_DIR/pg_hba.conf"

chown -R postgres:postgres "$PGCONF_DIR" "$PGDATA"

# 3. Start PostgreSQL cluster
echo "[ENTRYPOINT] Starting PostgreSQL $PGVERSION cluster..."
pg_ctlcluster "$PGVERSION" "$PGCLUSTER" start

# 4. Wait for PostgreSQL to be ready
echo "[ENTRYPOINT] Waiting for PostgreSQL to be ready..."
for i in {1..30}; do
    if pg_isready -h 127.0.0.1 -p 5432 -U postgres >/dev/null 2>&1; then
        echo "[ENTRYPOINT] PostgreSQL is ready on port 5432."
        break
    fi
    sleep 1
    if [ "$i" -eq 30 ]; then
        echo "[ENTRYPOINT ERROR] Timed out waiting for PostgreSQL to start." >&2
        cat "$PG_LOG" || true
        exit 1
    fi
done

# 5. Provision database, users, and PostGIS
echo "[ENTRYPOINT] Configuring users, database '$POSTGRES_DB', and PostGIS extensions..."

# Set password for superuser postgres
psql -h 127.0.0.1 -U postgres -c "ALTER USER postgres WITH ENCRYPTED PASSWORD '$POSTGRES_PASSWORD';"

# If a custom user is requested, create or update it
if [ "$POSTGRES_USER" != "postgres" ]; then
    USER_EXISTS=$(psql -h 127.0.0.1 -U postgres -tAc "SELECT 1 FROM pg_roles WHERE rolname='$POSTGRES_USER'")
    if [ "$USER_EXISTS" != "1" ]; then
        echo "[ENTRYPOINT] Creating role '$POSTGRES_USER'..."
        psql -h 127.0.0.1 -U postgres -c "CREATE USER \"$POSTGRES_USER\" WITH SUPERUSER ENCRYPTED PASSWORD '$POSTGRES_PASSWORD';"
    else
        psql -h 127.0.0.1 -U postgres -c "ALTER USER \"$POSTGRES_USER\" WITH ENCRYPTED PASSWORD '$POSTGRES_PASSWORD';"
    fi
fi

# Create target database if it does not exist
DB_EXISTS=$(psql -h 127.0.0.1 -U postgres -tAc "SELECT 1 FROM pg_database WHERE datname='$POSTGRES_DB'")
if [ "$DB_EXISTS" != "1" ]; then
    echo "[ENTRYPOINT] Creating database '$POSTGRES_DB' owned by '$POSTGRES_USER'..."
    psql -h 127.0.0.1 -U postgres -c "CREATE DATABASE \"$POSTGRES_DB\" OWNER \"$POSTGRES_USER\";"
fi

# Enable PostGIS extensions on target database
echo "[ENTRYPOINT] Enabling PostGIS extensions on database '$POSTGRES_DB'..."
psql -h 127.0.0.1 -U postgres -d "$POSTGRES_DB" -c "CREATE EXTENSION IF NOT EXISTS postgis;"
psql -h 127.0.0.1 -U postgres -d "$POSTGRES_DB" -c "CREATE EXTENSION IF NOT EXISTS postgis_topology;"

# 6. Save container environment for cron service
echo "[ENTRYPOINT] Syncing container environment for cron service..."
env | grep -v '^[[:space:]]*$' | grep -v 'affinity:container' > /etc/environment
chmod 0644 /etc/environment

# 7. Start cron service
echo "[ENTRYPOINT] Starting cron service for monthly downloads..."
service cron start

# 8. Trigger background download if RUN_ON_STARTUP is enabled
touch "$DOWNLOAD_LOG"
if [ "$RUN_ON_STARTUP" = "true" ]; then
    echo "[ENTRYPOINT] RUN_ON_STARTUP is true: initiating first download pipeline in background..."
    /usr/local/bin/download-monthly.sh >> "$DOWNLOAD_LOG" 2>&1 &
fi

# 9. Trap termination signals for graceful shutdown
cleanup() {
    echo ""
    echo "[ENTRYPOINT] Termination signal received. Stopping services gracefully..."
    service cron stop || true
    pg_ctlcluster "$PGVERSION" "$PGCLUSTER" stop -m fast
    echo "[ENTRYPOINT] PostgreSQL stopped cleanly. Exiting."
    exit 0
}
trap cleanup SIGTERM SIGINT

echo "======================================================================"
echo " System ready."
echo " PostgreSQL $PGVERSION listening on port 5432"
echo " Database: $POSTGRES_DB | User: $POSTGRES_USER"
echo " Cron: scheduled on the 1st of every month at 03:00 UTC"
echo "======================================================================"

# Stream logs to stdout
touch "$PG_LOG" "$DOWNLOAD_LOG"
tail -F "$PG_LOG" "$DOWNLOAD_LOG" &
TAIL_PID=$!

wait "$TAIL_PID"
